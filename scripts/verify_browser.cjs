/* Browser acceptance against an explicitly mocked local server. Never paid AI. */
const { createRequire } = require('node:module');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const requireFrontend = createRequire(path.join(root, 'frontend', 'package.json'));
const { chromium } = process.env.PLAYWRIGHT_MODULE ? require(process.env.PLAYWRIGHT_MODULE) : requireFrontend('playwright');
const base = process.env.LORE_TEST_URL || 'http://127.0.0.1:5173';
const output = path.join(root, 'runtime', 'browser-verification');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE_PATH ? { executablePath: process.env.BROWSER_EXECUTABLE_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', err => errors.push(err.message));
  try {
    const health = await (await context.request.get(`${base}/api/health`)).json();
    assert.equal(health.provider, 'mock', 'Refusing browser test against a paid provider');
    await page.goto(base);
    await page.getByText('모의 시연 모드', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, '01-empty.png'), fullPage: true });
    await page.locator('#source-text').fill('폭풍 도시, 기억의 등대, 마지막 배달부');
    await page.getByRole('button', { name: '재료 정리하기' }).click();
    await page.getByText('재료 정리 완료', { exact: false }).waitFor();
    await page.getByRole('button', { name: '첫 설정 만들기' }).click();
    await page.getByRole('button', { name: '이 설정 채택' }).waitFor();
    await page.waitForFunction(() => !document.querySelector('.decision-buttons button')?.disabled);
    const firstId = await page.evaluate(() => localStorage.getItem('loreforge.run'));
    const firstRun = await (await context.request.get(`${base}/api/runs/${firstId}`)).json();
    assert.equal(firstRun.status, 'completed');
    assert.equal(firstRun.usage.attempts, 5);
    assert(firstRun.revision);
    await page.locator('.view-switch button').filter({ hasText: '관계' }).click();
    await page.locator('.graph-list-items button').first().waitFor();
    assert.equal(await page.locator('.graph-list-items button').count(), 5);
    await page.getByRole('button', { name: '그래프 확대' }).click();
    await page.getByRole('button', { name: '그래프 축소' }).click();
    await page.getByRole('button', { name: '그래프 화면에 맞춤' }).click();
    await page.locator('.graph-list-items button').first().focus();
    await page.keyboard.press('Enter');
    await page.locator('.item-detail h3').waitFor();
    await page.screenshot({ path: path.join(output, '02-graph.png'), fullPage: true });
    await page.locator('.item-detail .evidence-card').first().click();
    await page.locator('.passage.highlighted').waitFor();
    assert((await page.locator('.passage.highlighted').innerText()).includes('리나'));
    await page.getByRole('button', { name: '첫 초안', exact: true }).click();
    await page.locator('.issue-toggle').first().click();
    await page.locator('.issue-expanded .evidence-card').first().click();
    await page.locator('.passage.highlighted').waitFor();
    await page.getByRole('button', { name: '수정본', exact: true }).click();
    assert.equal(await page.locator('.issue-card').count(), 0, 'Old issues leaked into revision');
    await page.locator('#decision-reason').fill('공개 모의 입력으로 상태 보존 확인');
    await page.getByRole('button', { name: '이 설정 채택' }).click();
    await page.getByRole('button', { name: '이 설정 이어쓰기' }).waitFor();
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: '근거와 함께 Markdown 내보내기' }).click();
    const downloaded = await downloadPromise;
    await downloaded.saveAs(path.join(output, 'export.md'));
    assert(fs.readFileSync(path.join(output, 'export.md'), 'utf8').includes('## passage-'));
    await page.reload();
    await page.getByRole('button', { name: '이 설정 이어쓰기' }).waitFor();
    assert.equal(await page.locator('#decision-reason').inputValue(), '공개 모의 입력으로 상태 보존 확인');
    // Force stale running GET to arrive after completed GET. It must not undo completion.
    const raceUrl = `**/api/runs/${firstId}`;
    const stable = await (await context.request.get(`${base}/api/runs/${firstId}`)).json();
    const stale = { ...stable, status: 'running', stage: 'review', decision: { status: 'pending', reason: '' } };
    let reads = 0;
    await page.route(raceUrl, async route => {
      if (route.request().method() !== 'GET') return route.continue();
      reads += 1;
      if (reads === 1) return route.fulfill({ json: stale });
      if (reads === 2) { await new Promise(resolve => setTimeout(resolve, 800)); return route.fulfill({ json: stale }); }
      return route.fulfill({ json: stable });
    });
    await page.reload();
    await page.getByRole('button', { name: '이 설정 이어쓰기' }).waitFor();
    await page.waitForTimeout(1000);
    assert(await page.getByRole('button', { name: '이 설정 이어쓰기' }).isEnabled(), 'Stale running response undid completion/decision');
    assert(reads >= 3, 'Race scenario did not trigger concurrent refreshes');
    await page.unroute(raceUrl);
    const afterGraph = await (await context.request.get(`${base}/api/runs/${firstId}`)).json();
    assert.equal(afterGraph.usage.attempts, firstRun.usage.attempts);
    await page.getByRole('button', { name: '이 설정 이어쓰기' }).click();
    await page.getByRole('button', { name: '이야기 이어가기' }).click();
    await page.getByRole('button', { name: '이 설정 채택' }).waitFor();
    await page.waitForFunction(() => !document.querySelector('.decision-buttons button')?.disabled);
    const secondId = await page.evaluate(() => localStorage.getItem('loreforge.run'));
    assert.notEqual(secondId, firstId);
    const continued = await (await context.request.get(`${base}/api/runs/${secondId}`)).json();
    assert(continued.context.documents.some(doc => doc.document_id === firstRun.revision.document_id && doc.version === 2));
    assert(!continued.context.documents.some(doc => doc.document_id === firstRun.draft.document_id && doc.version === 1));
    await page.getByRole('button', { name: '보류', exact: true }).click();
    await page.getByText('보류됨', { exact: true }).first().waitFor();
    assert.equal(await page.getByRole('button', { name: '이 설정 이어쓰기' }).count(), 0);

    // Exercise display limits with a browser-only fixture. Stored data is untouched.
    const graphUrl = `**/api/runs/${secondId}/graph?view=*`;
    const largeRef = `${continued.revision.document_id}:${continued.revision.version}`;
    const nodes = Array.from({ length: 35 }, (_, i) => ({ data: { id: `large:${i}`, label: `인물${i}`, type: 'person', status: 'pending', basis: 'explicit', document_ref: largeRef, evidence: [], issue_ids: [] } }));
    const edges = Array.from({ length: 65 }, (_, i) => ({ data: { id: `edge:${i}`, source: `large:${i % 30}`, target: `large:${(i + 1) % 30}`, label: '연결', type: 'related_to', status: 'pending', basis: 'explicit', document_ref: largeRef, evidence: [], issue_ids: [] } }));
    await page.route(graphUrl, route => route.fulfill({ json: { nodes, edges, warnings: ['검증용 부분 표시 경고'] } }));
    await page.reload();
    await page.getByRole('button', { name: '수정본', exact: true }).waitFor();
    await page.locator('.view-switch button').filter({ hasText: '관계' }).click();
    await page.getByText('표시 한도는 30개 항목·60개 관계입니다.', { exact: false }).waitFor();
    assert.equal(await page.locator('.graph-list-items button').count(), 90);
    await page.locator('#graph-search').fill('인물34');
    assert.equal(await page.locator('.graph-list-items button').count(), 1, 'A node outside initial limit must remain discoverable');
    await page.locator('#graph-type').selectOption('place');
    await page.getByText('조건에 맞는 항목이 없어요').waitFor();
    await page.unroute(graphUrl);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.reload();
    await page.getByRole('button', { name: '02 작업 문서' }).click();
    await page.locator('.story-document').waitFor();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'Horizontal viewport overflow');
    await page.screenshot({ path: path.join(output, '03-mobile.png'), fullPage: true });
    await page.getByRole('button', { name: '03 검토' }).click();
    await page.locator('#decision-reason').waitFor({ state: 'visible' });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: '새 작업' }).click();
    await page.locator('input[type=file]').setInputFiles({ name: 'public.md', mimeType: 'text/markdown', buffer: Buffer.from('공개 메모\n\n<script>window.evil=true</script>') });
    await page.waitForFunction(() => document.querySelector('#source-text').value.includes('<script>'));
    assert((await page.locator('#source-text').inputValue()).includes('<script>'));
    await page.getByRole('button', { name: '재료 정리하기' }).click();
    await page.getByText('재료 정리 완료', { exact: false }).waitFor();
    assert.equal(await page.evaluate(() => window.evil), undefined, 'Raw document HTML executed');
    // First-use navigation must work without spatial instructions on a narrow screen.
    const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const mobile = await mobileContext.newPage();
    mobile.setDefaultTimeout(15000);
    mobile.on('pageerror', err => errors.push(err.message));
    await mobile.goto(base);
    await mobile.getByRole('button', { name: '02 작업 문서' }).click();
    await mobile.getByRole('button', { name: '관계 그래프 보기', exact: true }).click();
    await mobile.getByRole('button', { name: '재료 입력으로 이동' }).click();
    assert.equal(await mobile.locator('#source-text').evaluate(el => document.activeElement === el), true);
    await mobile.locator('#source-text').fill('유리 사막, 기억을 파는 상인, 사라진 달');
    await mobile.getByRole('button', { name: '재료 정리하기' }).click();
    await mobile.getByRole('button', { name: '초안 요청으로 이동' }).click();
    await mobile.screenshot({ path: path.join(output, 'mobile-navigation-debug.png'), fullPage: true });
    assert.equal(await mobile.locator('#story-request').evaluate(el => document.activeElement === el), true);
    await mobile.getByRole('button', { name: '첫 설정 만들기' }).click();
    await mobile.getByRole('button', { name: '근거와 검토를 확인하고 채택 여부 결정' }).click();
    await mobile.locator('#decision-reason').waitFor({ state: 'visible' });
    assert.equal(await mobile.locator('#review-heading').evaluate(el => document.activeElement === el), true);
    const mobileId = await mobile.evaluate(() => localStorage.getItem('loreforge.run'));
    const mobileRun = await (await context.request.get(`${base}/api/runs/${mobileId}`)).json();
    const pendingFixture = { ...mobileRun, status: 'needs_attention', pending_issues: [{
      origin_run_id: mobileId, document_ref: `${mobileRun.draft.document_id}:1`,
      issue: { id: 'author-choice', kind: 'intent_question', reason: '사라진 달의 운명은 작가의 선택이 필요합니다.', suggestion: '봉인과 소멸 중 의도한 방향을 정해주세요.', status: 'open', evidence: [] },
      evidence_snapshots: [{ document_ref: `${mobileRun.draft.document_id}:1`, passage_id: 'p01', text: '달의 운명은 아직 결정되지 않았다.' }],
    }] };
    await mobile.route(`**/api/runs/${mobileId}`, route => route.fulfill({ json: pendingFixture }));
    await mobile.reload();
    await mobile.getByRole('button', { name: '03 검토' }).click();
    await mobile.locator('.pending-issue summary').click();
    assert((await mobile.locator('.pending-issue blockquote').innerText()).includes('달의 운명은 아직 결정되지 않았다.'));
    assert.equal(await mobile.locator('.issue-card').count(), 0, 'Original pending evidence must not become a current-version finding');
    await mobile.screenshot({ path: path.join(output, '04-pending-mobile.png'), fullPage: true });
    await mobile.getByRole('button', { name: '02 작업 문서' }).click();
    await mobile.getByRole('button', { name: '첫 초안', exact: true }).click();
    await mobile.getByRole('button', { name: '03 검토' }).click();
    await mobile.getByRole('button', { name: '최종 수정본 보기' }).click();
    assert(await mobile.locator('.story-document').isVisible());
    assert.equal(await mobile.locator('.version-tabs button.active').innerText(), '수정본');
    assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await mobileContext.close();
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify({ passed: true, provider: 'mock', first_run: firstId, continuation_run: secondId, checks: ['keyword generation','revision','graph node/edge keyboard navigation','evidence jump','version-scoped issues','accept/defer','export','reload persistence','accepted-only continuation','graph no AI calls','30/60 display limit','filtered beyond-limit node','partial/empty graph','390px mobile panels','TXT/MD import','HTML inert','first-use mobile focus and next actions','pending original-version evidence'], page_errors: errors }, null, 2));
    console.log(`Browser acceptance passed. Artifacts: ${output}`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
